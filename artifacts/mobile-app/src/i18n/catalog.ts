const catalogs: Record<AppLanguage, Record<MessageKey, string>> = { en, ar, de };

export function textDirection(language: AppLanguage): "rtl" | "ltr" {
  return language === "ar" ? "rtl" : "ltr";
}

export function translate(language: AppLanguage, key: MessageKey): string {
  return catalogs[language][key] ?? en[key];
}

export function catalogKeys(language: AppLanguage): string[] {
  return Object.keys(catalogs[language]);
}
